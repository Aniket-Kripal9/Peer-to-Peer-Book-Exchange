async function seedDatabase() {
  try {
    await mongoose.connect(process.env.MONGO_URI);
    console.log('Connected to MongoDB Atlas...');

    // Clear existing books and populate with real covers
    await Book.deleteMany({});
    console.log('Cleared existing books from database.');

    const inserted = await Book.insertMany(realBooks);
    console.log(`Successfully seeded ${inserted.length} real books into MongoDB Atlas!`);

    await mongoose.connection.close();
    console.log('Database connection closed.');
    process.exit(0);
  } catch (err) {
    console.error('Seeding error:', err);
    process.exit(1);
  }
}

seedDatabase();